//! Traductions. Chaque langue est un `match` exhaustif sur [`K`] : une clé ajoutée sans
//! traduction ne compile pas. Ajouter une langue = une variante de [`Lang`] et une fonction.
//!
//! Règle de rédaction (utilisateur, 20/10) : chaque information une seule fois, libellés courts,
//! aucune phrase d'accueil ni de remplissage ; une aide seulement là où l'action n'est pas
//! évidente.

use rc_manager_shared::ErrorCode;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    Fr,
    En,
}

impl Lang {
    pub fn code(self) -> &'static str {
        match self {
            Lang::Fr => "fr",
            Lang::En => "en",
        }
    }
    pub fn from_code(s: &str) -> Option<Lang> {
        match s {
            "fr" => Some(Lang::Fr),
            "en" => Some(Lang::En),
            _ => None,
        }
    }
    /// Langue du navigateur (`navigator.language`, `fr-FR`, `en-GB`…) : français s'il commence
    /// par « fr », anglais pour tout le reste.
    pub fn from_browser(tag: &str) -> Lang {
        if tag.trim().to_ascii_lowercase().starts_with("fr") { Lang::Fr } else { Lang::En }
    }
    pub fn next(self) -> Lang {
        match self {
            Lang::Fr => Lang::En,
            Lang::En => Lang::Fr,
        }
    }
}

